// The two design-token guards over the console's tree (ADR 0017) — Cando's
// `packages/ui/scripts/check-design-tokens.mjs`, pointed at this app. All the logic is in
// `../src/tokens/*.ts`, which are pure functions with their own unit tests; this file is only the
// file walking and the exit code.
//
//   Rule A — a colour literal in a component, outside the sanctioned exceptions; and a colour
//            literal inside `@theme` in `index.css`, where a mode is impossible.
//   Rule B — a base token identical across modes while its derived family flips.
//
// Neither overlaps `check-token-utilities.mjs`, which asserts that a token utility *resolves*.
// This needs no build: it reads source, so it costs milliseconds and runs anywhere.
//
// Imported from `.mjs` with a `.ts` specifier on purpose — Node 24 strips types natively, which
// is what lets the logic live in a typechecked, unit-tested module without a build step.
// `.github/workflows/ci.yml` pins `node-version: 24` and the root `engines` says `>=24`; a runner
// older than 22.18 would need `--experimental-strip-types`.
import { readdir, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import {
  blankHtmlComments,
  COLOUR_EXCEPTIONS,
  checkColourLiterals,
  findStaleExceptions,
  findThemeColourLiterals,
} from "../src/tokens/colour-literals.ts";
import { checkModePairs, parseModePairs } from "../src/tokens/mode-pairs.ts";

const root = fileURLToPath(new URL("../../..", import.meta.url));
const GLOBALS = "apps/web/src/index.css";
const SOURCE_DIRS = ["apps/web/src"];

/**
 * Vite's other build input, beside the TypeScript tree. `index.html` is where the two
 * `theme-color` metas live, and an inline `<style>` or an attribute colour added there would be as
 * invisible to a reviewer as one in a class string — so it goes through Rule A like a component,
 * with its comments blanked first (raised by Greptile on #25). `index.css` is the token file
 * itself and is read separately below: `:root`/`.dark` are *where* a literal belongs, `@theme` is
 * where one is always wrong, and Rule B compares the pairs.
 */
const HTML_FILES = ["apps/web/index.html"];

/**
 * Two exclusions, both for the same reason rather than for convenience: a guard's own fixtures
 * and its own exception list are literals of exactly the kind it reports, so scanning them would
 * make every test of this rule a violation of it and every narrowed exception a finding. Neither
 * `*.test.*` nor `src/tokens/` renders any UI — the latter is pure text analysis with no JSX in
 * it at all.
 *
 * `routeTree.gen.ts` is generated by the TanStack Router plugin, and is excluded from Biome for
 * the same reason.
 */
const SKIP_FILE = /\.test\.(ts|tsx)$|routeTree\.gen\.ts$/;
const SKIP_DIR = ["apps/web/src/tokens"];

async function* sources(dir) {
  if (SKIP_DIR.includes(dir)) return;
  for (const entry of await readdir(`${root}${dir}`, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === "dist") continue;
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) yield* sources(path);
    else if (/\.tsx?$/.test(entry.name) && !SKIP_FILE.test(entry.name)) yield path;
  }
}

const files = [];
for (const dir of SOURCE_DIRS) {
  for await (const path of sources(dir)) {
    files.push({ path, source: await readFile(`${root}${path}`, "utf8") });
  }
}
for (const path of HTML_FILES) {
  files.push({ path, source: blankHtmlComments(await readFile(`${root}${path}`, "utf8")) });
}

const globals = await readFile(`${root}${GLOBALS}`, "utf8");
const pairs = parseModePairs(globals);

const literals = checkColourLiterals(files);
const inTheme = findThemeColourLiterals(globals);
const stale = findStaleExceptions(files);
const flips = checkModePairs(pairs);

console.log(
  `Rule A: scanned ${files.length} sources with ${COLOUR_EXCEPTIONS.length} sanctioned exception${COLOUR_EXCEPTIONS.length === 1 ? "" : "s"}, plus every @theme block in ${GLOBALS}`,
);
console.log(`Rule B: compared ${pairs.length} tokens declared in both :root and .dark`);

let failed = false;

if (literals.length) {
  failed = true;
  console.error(
    `\n${literals.length} hardcoded colour${literals.length === 1 ? "" : "s"} — invisible in light and broken in dark, with nothing else that would catch it (ADR 0017):`,
  );
  for (const problem of literals) console.error(`  ${problem}`);
  console.error(
    "\nUse a token. If the colour genuinely cannot be one, add it to COLOUR_EXCEPTIONS in apps/web/src/tokens/colour-literals.ts with a reason.",
  );
}

if (inTheme.length) {
  failed = true;
  console.error(
    `\n${inTheme.length} colour literal${inTheme.length === 1 ? "" : "s"} inside @theme, where a mode is impossible (ADR 0017):`,
  );
  for (const literal of inTheme) {
    console.error(`  ${GLOBALS}:${literal.line}  ${literal.text}  (${literal.kind})`);
  }
  console.error(
    "\nDeclare the value in :root and .dark, and leave the @theme entry holding a var() — the shape the managed block already uses for every colour.",
  );
}

if (stale.length) {
  failed = true;
  console.error(
    `\n${stale.length} exception${stale.length === 1 ? "" : "s"} match nothing any more:`,
  );
  for (const problem of stale) console.error(`  ${problem}`);
  console.error("\nRemove them — a stale exception silently covers the next literal at that path.");
}

if (flips.length) {
  failed = true;
  console.error(
    `\n${flips.length} base token${flips.length === 1 ? "" : "s"} did not move between modes while its derived family did (ADR 0017):`,
  );
  for (const problem of flips) console.error(`  ${problem}`);
  console.error(
    "\nThis is the shape of Cando's --destructive bug (its CAN-130): the family moved to a new hue and the base was left behind.",
  );
}

if (failed) process.exit(1);
console.log("\nNo hardcoded colours, and no base token left behind by its family.");
